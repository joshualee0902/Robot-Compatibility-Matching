"""Fill the README results block from files in reports/ (and screenshots from docs/screenshots/).

Nothing here is typed by hand: every table is copied from a generated report, and the plain-English
verdict lines are computed from the paired confidence intervals in reports/backtest_results.csv.
If a report does not exist yet, the block says so.

    python -m analytics.report            # rewrite the block in README.md
    python -m analytics.report --check    # exit 1 if README.md differs (used in CI)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

START = "<!-- RESULTS:START (generated by `make report`; do not edit by hand) -->"
END = "<!-- RESULTS:END -->"
NOT_YET = "_Not generated yet._"


def _read(path: Path) -> str | None:
    return path.read_text().strip() if path.exists() else None


def verdicts(summary: pd.DataFrame) -> list[str]:
    """One sentence per paired comparison, from the bootstrap CIs. 'gap' is skipped: it is
    biased toward the OPR baseline by construction."""
    names = {"spearman": "Spearman correlation", "top3": "top-3 hit rate"}
    lines = []
    for metric, label in names.items():
        for other, other_label in (("opr", "plain OPR"), ("seeding", "seeding")):
            row = summary[(summary["metric"] == metric) & (summary["method"] == f"knn - {other}")]
            if row.empty:
                continue
            r = row.iloc[0]
            if pd.isna(r["mean"]):
                continue
            if r["ci_low"] > 0:
                outcome = "complementary k-NN is better"
            elif r["ci_high"] < 0:
                outcome = "complementary k-NN is worse"
            else:
                outcome = "the CI includes 0, so there is no clear difference"
            lines.append(f"- {label}, k-NN minus {other_label}: {r['mean']:+.3f} "
                         f"(95% CI [{r['ci_low']:+.3f}, {r['ci_high']:+.3f}], {int(r['n_events'])} events): {outcome}.")
    return lines


def render(report_dir="reports", shots_dir="docs/screenshots") -> str:
    rep, shots = Path(report_dir), Path(shots_dir)
    parts = []

    def section(title, body):
        parts.append(f"### {title}\n\n{body}\n")

    section("Data pulled", _read(rep / "data_counts.md") or f"{NOT_YET} Run `make data`.")

    mae = _read(rep / "opr_mae_by_k.md")
    if mae:
        img = f"\n\n![MAE versus k]({(rep / 'opr_mae_by_k.png').as_posix()})" if (rep / "opr_mae_by_k.png").exists() else ""
        section("Alliance-score prediction error versus matches observed",
                "Mean absolute error of next-match alliance score predictions; SE is across events.\n\n" + mae + img)
    else:
        section("Alliance-score prediction error versus matches observed", f"{NOT_YET} Run `make opr-eval`.")

    bt = _read(rep / "backtest_results.md")
    if bt:
        text = "Means over events with bootstrap 95% confidence intervals (fixed seed).\n\n" + bt
        csv = rep / "backtest_results.csv"
        if csv.exists():
            v = verdicts(pd.read_csv(csv))
            if v:
                text += "\n\nPaired comparisons (computed from the table above):\n\n" + "\n".join(v)
        section("Backtest", text)
    else:
        section("Backtest", f"{NOT_YET} Run `make backtest`.")

    weights = _read(rep / "fitted_weights.md")
    section("Fitted feature weights",
            weights + "\n\nFitted on all events, so descriptive only; the backtest never uses these."
            if weights else f"{NOT_YET} Run `make backtest`.")

    images = sorted(shots.glob("*.png")) if shots.exists() else []
    if images:
        section("Screenshots", "\n\n".join(f"![{p.stem}]({p.as_posix()})" for p in images))
    else:
        section("Screenshots", f"{NOT_YET} Add PNGs of the Alliance Selection screen to `docs/screenshots/`.")
    return "\n".join(parts).rstrip() + "\n"


def update_readme(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise ValueError("README.md is missing the RESULTS markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n\n{block}\n{END}{tail}"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--readme", default="README.md")
    p.add_argument("--reports", default="reports")
    p.add_argument("--screenshots", default="docs/screenshots")
    p.add_argument("--check", action="store_true", help="fail if the README block is out of date")
    args = p.parse_args(argv)

    readme = Path(args.readme)
    current = readme.read_text()
    updated = update_readme(current, render(args.reports, args.screenshots))
    if args.check:
        if updated != current:
            print("README results block is out of date. Run `make report` and commit.", file=sys.stderr)
            return 1
        print("README results block is up to date.")
        return 0
    readme.write_text(updated)
    print(f"updated {readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
